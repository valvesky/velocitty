//! In-process error log. F3 paints it over the framebuffer.

const std = @import("std");

const cap = 48;
const line_cap = 120;

const bg: u32 = 0xFF1D2021;
const fg: u32 = 0xFFEBDBB2;
const accent: u32 = 0xFFFABD2F;
const dim: u32 = 0xFFA89984;

var lines: [cap][line_cap]u8 = undefined;
var lens: [cap]u8 = @splat(0);
var head: u8 = 0;
var used: u8 = 0;
var last: [line_cap]u8 = undefined;
var last_len: u8 = 0;
var last_repeat: u32 = 0;
var glyph_logged: u32 = 0;

pub var visible: bool = false;

pub fn count() u8 {
    return used;
}

pub fn toggle() bool {
    visible = !visible;
    return visible;
}

pub fn log(comptime fmt: []const u8, args: anytype) void {
    var buf: [line_cap]u8 = undefined;
    const msg = std.fmt.bufPrint(&buf, fmt, args) catch {
        push("log truncated");
        return;
    };
    push(msg);
}

pub fn glyphErr(codepoint: u21, err: anyerror) void {
    if (glyph_logged >= 8) {
        if (glyph_logged == 8) {
            glyph_logged = 9;
            push("glyph errors suppressed");
        }
        return;
    }
    glyph_logged += 1;
    log("glyph U+{X}: {}", .{ codepoint, err });
}

pub fn paint(pixels: []u32, width: u32, height: u32, status: []const u8) void {
    if (width == 0 or height == 0) return;
    const scale: u32 = if (width >= 960) 2 else 1;
    const pad: u32 = 6 * scale;
    const gh: u32 = 8 * scale;
    const gw: u32 = 8 * scale;
    const title = "F3 DEBUG";
    const rows: u32 = 2 + @as(u32, used);
    const panel_h = @min(height, pad * 2 + rows * gh + pad);
    fill(pixels, width, height, 0, 0, width, panel_h, bg);

    var y: u32 = pad;
    text(pixels, width, height, pad, y, scale, title, accent);
    const hint = "press F3 to close";
    const hint_x = pad + @as(u32, title.len + 2) * gw;
    text(pixels, width, height, hint_x, y, scale, hint, dim);
    y += gh;

    text(pixels, width, height, pad, y, scale, status, dim);
    y += gh;

    var i: u8 = 0;
    while (i < used) : (i += 1) {
        const idx = (@as(u16, head) + cap - used + i) % cap;
        const n = lens[idx];
        const slice = lines[idx][0..n];
        if (i + 1 == used and last_repeat > 1) {
            var extra: [line_cap]u8 = undefined;
            const shown = std.fmt.bufPrint(&extra, "{s}  (x{d})", .{ slice, last_repeat }) catch slice;
            text(pixels, width, height, pad, y, scale, shown, fg);
        } else {
            text(pixels, width, height, pad, y, scale, slice, fg);
        }
        y += gh;
        if (y + gh > height) break;
    }
}

fn push(msg: []const u8) void {
    if (last_len != 0 and last_len == msg.len and std.mem.eql(u8, last[0..last_len], msg)) {
        last_repeat += 1;
        return;
    }
    const n = @min(msg.len, line_cap);
    const i = head;
    @memcpy(lines[i][0..n], msg[0..n]);
    lens[i] = @intCast(n);
    head = @intCast((@as(u16, head) + 1) % cap);
    if (used < cap) used += 1;
    @memcpy(last[0..n], msg[0..n]);
    last_len = @intCast(n);
    last_repeat = 1;
}

fn fill(pixels: []u32, width: u32, height: u32, x0: u32, y0: u32, w: u32, h: u32, color: u32) void {
    const x1 = @min(width, x0 + w);
    const y1 = @min(height, y0 + h);
    var y = y0;
    while (y < y1) : (y += 1) {
        const row = pixels[y * width + x0 .. y * width + x1];
        @memset(row, color);
    }
}

fn text(pixels: []u32, width: u32, height: u32, x0: u32, y0: u32, scale: u32, s: []const u8, color: u32) void {
    var x = x0;
    for (s) |ch| {
        blitChar(pixels, width, height, x, y0, scale, ch, color);
        x += 8 * scale;
        if (x >= width) break;
    }
}

fn blitChar(pixels: []u32, width: u32, height: u32, x0: u32, y0: u32, scale: u32, ch: u8, color: u32) void {
    const glyph = glyphBits(ch);
    var row: u32 = 0;
    while (row < 8) : (row += 1) {
        const bits = glyph[row];
        var col: u32 = 0;
        while (col < 8) : (col += 1) {
            if (bits & (@as(u8, 1) << @intCast(col)) == 0) continue;
            var sy: u32 = 0;
            while (sy < scale) : (sy += 1) {
                const y = y0 + row * scale + sy;
                if (y >= height) continue;
                var sx: u32 = 0;
                while (sx < scale) : (sx += 1) {
                    const x = x0 + col * scale + sx;
                    if (x >= width) continue;
                    pixels[y * width + x] = color;
                }
            }
        }
    }
}

fn glyphBits(ch: u8) *const [8]u8 {
    if (ch < 32 or ch > 126) return &font8[0];
    return &font8[ch - 32];
}

