test "log rings and dedups" {
    visible = false;
    used = 0;
    head = 0;
    last_len = 0;
    last_repeat = 0;
    glyph_logged = 0;
    log("hello {d}", .{1});
    log("hello {d}", .{1});
    try std.testing.expectEqual(@as(u8, 1), count());
    try std.testing.expectEqual(@as(u32, 2), last_repeat);
    log("other", .{});
    try std.testing.expectEqual(@as(u8, 2), count());

    var pix: [64 * 32]u32 = @splat(0);
    paint(&pix, 64, 32, "status");
    var lit: usize = 0;
    for (pix) |p| {
        if (p != 0) lit += 1;
    }
    try std.testing.expect(lit > 20);
}
